// Assembles .design/SPEC.md from .design/spec/NN-*.md (filename order).
// Refuses when the same exported TypeScript identifier is declared with different text in two files (§50.7 rule 5),
// ignoring trailing `//` comments and surrounding whitespace so text-identical mirrors pass.
// Usage: node .design/spec/assemble.mjs   (from the repo root or anywhere; paths are resolved from this file)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const parts = readdirSync(here).filter((f) => /^\d\d-.*\.md$/.test(f)).sort();
const texts = parts.map((f) => ({ file: f, text: readFileSync(join(here, f), 'utf8').replace(/\r\n/g, '\n') }));

// --- rule 5 check -------------------------------------------------------------------------------
const decl = /^export (?:interface|type|const|function|class|abstract class) ([A-Za-z_][A-Za-z0-9_]*)\b[^\n]*$/gm;
const seen = new Map(); // name -> { file, text }
const errors = [];
function declarationText(text, start) {
  // take from the declaration line to the end of the statement: a `;`-terminated line for types/consts, or the matching `}` for blocks
  const lines = text.slice(start).split('\n');
  const out = [];
  let depth = 0;
  for (const raw of lines) {
    const line = raw.replace(/\s*\/\/.*$/, '').trimEnd();
    out.push(line);
    depth += (line.match(/{/g) ?? []).length - (line.match(/}/g) ?? []).length;
    if (depth <= 0 && (/;\s*$/.test(line) || /}\s*$/.test(line) || /\)\s*:\s*[^;]*;?\s*$/.test(line))) break;
    if (out.length > 200) break;
  }
  return out.join('\n').trim();
}
for (const { file, text } of texts) {
  for (const m of text.matchAll(decl)) {
    const name = m[1];
    const body = declarationText(text, m.index);
    if (seen.has(name)) {
      const prev = seen.get(name);
      if (prev.file !== file && prev.body !== body) errors.push(`${name}: declared in ${prev.file} and differently in ${file}`);
    } else seen.set(name, { file, body });
  }
}
if (errors.length) {
  console.error('assemble.mjs: refused — redefined exported identifiers (§50.7 rule 5):\n  ' + errors.join('\n  '));
  process.exit(1);
}

// --- table of contents ---------------------------------------------------------------------------
const slug = (s) => s.toLowerCase().replace(/<!--.*?-->/g, '').replace(/[`*_]/g, '').replace(/[^a-z0-9§.\- ]+/g, '').trim().replace(/\s+/g, '-');
const toc = [];
for (const { file, text } of texts) {
  const title = text.split('\n')[0].replace(/^#\s*/, '');
  toc.push(`- **${file}** — ${title}`);
  for (const m of text.matchAll(/^(##|###) (.+)$/gm)) {
    const clean = m[2].replace(/<!--.*?-->/g, '').trim();
    toc.push(`${m[1] === '##' ? '  - ' : '    - '}[${clean}](#${slug(clean)})`);
  }
}

