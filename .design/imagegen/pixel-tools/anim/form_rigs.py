"""Bone rigs for rig_forms.py: the Majin and Tenjin forms, front and back, in source pixels of the 1024² sprites.

Each bone: role (ground, body, float, head, arm, wing, fin, tail, antenna, cape), pivot, end (the segment that claims
the nearest pixels), and optionally parent (default: the body), depth (draw order where parts overlap, higher in
front), box (u0, v0, u1, v1: the only pixels it may own), r (a thick bone), sign / phase / amp / idx (motion tweaks;
idx orders a tail or fin chain). `ground` is fixed: legs, feet or a pedestal.
"""


def b(role, pivot, end=None, **kw):
    return dict(role=role, pivot=pivot, end=end or pivot, **kw)


def stander(ground, body, **parts):
    """A creature on its feet: a fixed ground, a body over it, the rest parented to the body unless told otherwise."""
    return dict(ground=b('ground', *ground[:2], depth=1, box=ground[2]), body=b('body', *body[:2], box=body[2], r=body[3] if len(body) > 3 else 0), **parts)


def floater(body, **parts):
    return dict(body=b('float', *body[:2], r=body[2] if len(body) > 2 else 0, box=None), **parts)


