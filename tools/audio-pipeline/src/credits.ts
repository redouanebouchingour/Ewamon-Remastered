/**
 * Phase E4 — audio credits generated from `.design/audio/sources.json`: `assets-src/audio/CREDITS.md` (one row per
 * source file: title, author, licence, page, the job ids it fills) plus the licence texts found in
 * `assets-src/audio/licenses/`, and a plain-text copy the client ships at `public/audio/CREDITS.txt`. CC0 asks for no
 * attribution; the credits are a courtesy and a provenance record. Output is deterministic (no dates).
 */
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { IngestPaths } from './paths.js';
import type { ClassifiedJob, SourceEntry, SourcesFile } from './sources.js';

export interface CreditRow {
  readonly file: string;
  readonly title: string;
  readonly author: string;
  readonly url: string;
  readonly licence: string;
  readonly licenceFile: string | null;
  /** job ids filled directly from this file */
  readonly direct: readonly string[];
  /** job ids derived from it (theme layers, sfx variants) */
  readonly derived: readonly string[];
}

/** The files an entry credits: its own file, or each part of a premix (with the part's attribution). */
function credited(e: SourceEntry): { file: string; e: SourceEntry }[] {
  if (e.parts === undefined || e.parts.length === 0) return [{ file: e.file, e }];
  return e.parts.map((p) => ({
    file: p.file,
    e: { file: p.file, licence: e.licence, author: p.author, url: p.url, ...(p.title !== undefined ? { title: p.title } : {}), ...(p.licenceFile !== undefined ? { licenceFile: p.licenceFile } : {}) },
  }));
}

/** One row per distinct source file (a premix is credited through its parts), sorted by author then file. */
export function creditRows(sources: SourcesFile, classified: readonly ClassifiedJob[]): CreditRow[] {
  const rows = new Map<string, { e: SourceEntry; direct: string[]; derived: string[] }>();
  for (const [id, entry] of Object.entries(sources)) {
    for (const { file, e } of credited(entry)) {
      const r = rows.get(file) ?? { e, direct: [], derived: [] };
      if (!r.direct.includes(id)) r.direct.push(id);
      rows.set(file, r);
    }
  }
  for (const c of classified) {
    if (c.role.kind !== 'layer' && c.role.kind !== 'variant') continue;
    const from = sources[c.role.from];
    if (from !== undefined) for (const { file } of credited(from)) rows.get(file)?.derived.push(c.id);
  }
  return [...rows.entries()]
    .map(([file, r]) => ({
      file,
      title: r.e.title ?? path.posix.basename(file.replace(/\\/g, '/')).replace(/\.[^.]+$/, ''),
      author: r.e.author,
      url: r.e.url,
      licence: r.e.licence,
      licenceFile: r.e.licenceFile ?? null,
      direct: r.direct.sort(),
      derived: r.derived.sort(),
    }))
    .sort((a, b) => (a.author.toLowerCase() < b.author.toLowerCase() ? -1 : a.author.toLowerCase() > b.author.toLowerCase() ? 1 : a.file < b.file ? -1 : 1));
}

export function listLicenceTexts(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => statSync(path.join(dir, f)).isFile())
    .sort();
}

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function usedFor(r: CreditRow, max = 6): string {
  const shown = r.direct.slice(0, max).map((id) => `\`${id}\``);
  const more = r.direct.length - shown.length;
  return `${shown.join(', ')}${more > 0 ? ` +${more} more` : ''}${r.derived.length > 0 ? ` (+${r.derived.length} derived)` : ''}`;
}

export function renderCreditsMarkdown(rows: readonly CreditRow[], licenceTexts: readonly string[]): string {
  const lines: string[] = [
    '# Ewamon Remastered — audio credits',
    '',
    '<!-- Generated by `pnpm --filter @ewa/audio-pipeline credits` from `.design/audio/sources.json`. Do not edit by hand. -->',
    '',
  ];
  if (rows.length === 0) {
    lines.push('No third-party audio is mapped yet (`.design/audio/sources.json` is empty or absent). The shipped audio is placeholder synthesis made by the pipeline itself.', '');
  } else {
    const authors = new Set(rows.map((r) => r.author)).size;
    lines.push(
      `The game's music, ambience and sound effects use ${rows.length} source file${rows.length === 1 ? '' : 's'} by ${authors} author${authors === 1 ? '' : 's'}, all released under ` +
        '[CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/) (public domain dedication). CC0 requires no attribution; these credits are given with thanks and as a provenance record. ' +
        'Theme layers marked "derived" are filtered variants of a credited track made by the audio pipeline; derived sound-effect variants are pitch-shifted copies.',
      '',
      '| Title | Author | Licence | Source | File | Used for |',
      '|---|---|---|---|---|---|',
    );
    for (const r of rows) lines.push(`| ${cell(r.title)} | ${cell(r.author)} | ${cell(r.licence)} | <${r.url}> | \`${cell(r.file)}\` | ${usedFor(r)} |`);
    lines.push('');
  }
  lines.push('## Licence texts', '');
  if (licenceTexts.length === 0) lines.push('None yet. Put each pack\'s own licence file (and `CC0-1.0.txt`) in `assets-src/audio/licenses/`.');
  else for (const f of licenceTexts) lines.push(`- [\`licenses/${f}\`](licenses/${encodeURI(f)})`);
  const missing = rows.filter((r) => r.licenceFile !== null && !licenceTexts.includes(r.licenceFile)).map((r) => r.licenceFile!);
  if (missing.length > 0) lines.push('', `Referenced but not present: ${[...new Set(missing)].sort().map((f) => `\`${f}\``).join(', ')}.`);
  lines.push('');
  return lines.join('\n');
}

export function renderCreditsText(rows: readonly CreditRow[]): string {
  const lines: string[] = ['EWAMON REMASTERED - AUDIO CREDITS', ''];
  if (rows.length === 0) {
    lines.push('No third-party audio is used in this build.', '');
    return lines.join('\n');
  }
  lines.push(
    'Music, ambience and sound effects from the following sources, all released under',
    'CC0 1.0 Universal (public domain dedication): https://creativecommons.org/publicdomain/zero/1.0/',
    'No attribution is required; credited with thanks.',
    '',
  );
  for (const r of rows) {
    lines.push(`${r.title} - ${r.author}`, `  ${r.url}`, `  Licence: ${r.licence}`, '');
  }
  return lines.join('\n');
}

/** Write `assets-src/audio/CREDITS.md` and `<outDir>/CREDITS.txt`. */
export function writeCredits(sources: SourcesFile, classified: readonly ClassifiedJob[], ingest: Pick<IngestPaths, 'credits' | 'licences'>, outDir: string): { markdown: string; text: string; rows: number } {
  const rows = creditRows(sources, classified);
  const md = renderCreditsMarkdown(rows, listLicenceTexts(ingest.licences));
  mkdirSync(path.dirname(ingest.credits), { recursive: true });
  writeFileSync(ingest.credits, md);
  const text = path.join(outDir, 'CREDITS.txt');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(text, renderCreditsText(rows));
  return { markdown: ingest.credits, text, rows: rows.length };
}
