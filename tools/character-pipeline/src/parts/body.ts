/**
 * The shared body: skin head, faces, arms and legs for every pose, per authored facing (D toward the camera,
 * U away, L profile facing screen-left; R is L mirrored).
 *
 * Template space (the compositor paints 3 rows lower, compose.ts BASE_DY): hair top ≈ row 1, eyes 12–13, chin 19,
 * torso 20–31, hands 30–32, legs 29–42 (soles on 42 → cell row 45). A 42-texel chibi adult (≈ 2.6 heads) whose
 * head is 16 texels wide. Light comes from the upper left: highlights on upper-left planes, shadows on the right
 * and underneath.
 *
 * Arm slots: A = upper sleeve, B = forearm (sleeve, skin or glove), C = hand (skin or glove). Leg slots: A = trousers,
 * B = shin (trousers or boot shaft), C = shoe.
 */
