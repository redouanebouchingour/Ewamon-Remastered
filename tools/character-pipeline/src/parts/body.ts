/** The far arm in profile: the near arm's opposite swing, one texel up and right, drawn behind the torso. */
const FAR_OF: Readonly<Record<string, string | null>> = { side: null, fwd: 'back', back: 'fwd', runFwd: 'runBack', runBack: 'runFwd' };

function farArm(pose: ArmPose): Tpl | null {
  const k = FAR_OF[pose];
  if (k === null || k === undefined) return null;
  const t = ARM_L[k]!;
  return { y: t.y - 1, x: 2, rows: t.rows };
}

export const ARMS: PartDef = {
  kinds: {
    arm: { D: (p: Pose) => (p.arms === 'cheer1' || p.arms === 'cheer2' ? null : ARMS_D[p.arms] ?? ARMS_D.down!), U: (p: Pose) => ARMS_U[p.arms] ?? ARMS_U.down!, L: (p: Pose) => ARM_L[p.arms] ?? ARM_L.side! },
    armRaised: { D: (p: Pose) => ARMS_RAISED_D[p.arms] ?? null },
    armFar: { L: (p: Pose) => farArm(p.arms) },
  },
};

