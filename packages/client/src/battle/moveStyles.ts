/** The `style_*` VFX id of a move, or undefined (status moves). */
export function styleVfxOf(moveId: string): `style_${MoveStyle}` | undefined {
  const s = Object.prototype.hasOwnProperty.call(MOVE_STYLE, moveId) ? MOVE_STYLE[moveId] : undefined;
  return s === undefined ? undefined : `style_${s}`;
}
